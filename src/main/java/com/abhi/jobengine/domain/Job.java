package com.abhi.jobengine.domain;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.PrePersist;
import jakarta.persistence.PreUpdate;
import jakarta.persistence.Table;
import jakarta.validation.constraints.Min;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

import java.time.Instant;
import java.time.temporal.ChronoUnit;
import java.util.Map;
import java.util.UUID;

/**
 * A unit of asynchronous work submitted by a tenant. Mapped to the {@code jobs} table
 * created by {@code V1__create_jobs_table.sql}; column names, types and defaults here must
 * stay in sync with the migrations ({@code ddl-auto=validate} checks this at startup).
 *
 * <p>All timestamps are {@link Instant}s stored as {@code TIMESTAMPTZ} (UTC).
 */
@Entity
@Table(name = "jobs")
@Getter
@Setter
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class Job {

    public static final int DEFAULT_PRIORITY = 0;
    public static final int DEFAULT_MAX_ATTEMPTS = 3;

    /** Primary key, generated by Hibernate (random UUID) before insert. */
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    @Column(name = "id", nullable = false, updatable = false)
    private UUID id;

    /** Tenant that owns the job. Jobs of one tenant execute sequentially. */
    @NotBlank
    @Size(max = 100)
    @Column(name = "tenant_id", nullable = false, updatable = false, length = 100)
    private String tenantId;

    /** Current lifecycle state. */
    @NotNull
    @Builder.Default
    @Enumerated(EnumType.STRING)
    @Column(name = "job_status", nullable = false, length = 20)
    private JobStatus jobStatus = JobStatus.PENDING;

    /** Selects the executor that handles the job. */
    @NotNull
    @Enumerated(EnumType.STRING)
    @Column(name = "job_type", nullable = false, updatable = false, length = 50)
    private JobType jobType;

    /**
     * Job input as a JSON object, stored as {@code JSONB}. Serialized by Hibernate's JSON
     * format mapper (Jackson); on load, numbers come back as Integer/Long/Double/BigDecimal
     * and nested objects as maps, and JSONB does not preserve key order.
     */
    @NotNull
    @JdbcTypeCode(SqlTypes.JSON)
    @Column(name = "payload", nullable = false, columnDefinition = "jsonb")
    private Map<String, Object> payload;

    /** Higher values are dispatched first. Defaults to {@value #DEFAULT_PRIORITY}. */
    @NotNull
    @Builder.Default
    @Column(name = "priority", nullable = false)
    private Integer priority = DEFAULT_PRIORITY;

    /** Number of times execution has been started. */
    @NotNull
    @Min(0)
    @Builder.Default
    @Column(name = "attempt_count", nullable = false)
    private Integer attemptCount = 0;

    /** Maximum number of attempts before the job is marked {@link JobStatus#FAILED}. */
    @NotNull
    @Min(1)
    @Builder.Default
    @Column(name = "max_attempts", nullable = false)
    private Integer maxAttempts = DEFAULT_MAX_ATTEMPTS;

    /** Earliest time the job may run (or be retried). Defaults to the creation time. */
    @Column(name = "next_run_at", nullable = false)
    private Instant nextRunAt;

    /** Identifier of the worker / application instance holding the job. */
    @Size(max = 255)
    @Column(name = "locked_by")
    private String lockedBy;

    /** When the current worker's lease expires; after that the job may be reclaimed. */
    @Column(name = "lease_until")
    private Instant leaseUntil;

    /** Last heartbeat from the executing worker. */
    @Column(name = "heartbeat")
    private Instant heartbeat;

    /**
     * Incremented on every claim. Updates from a worker must match the token it claimed with,
     * so a stale worker whose lease was taken over cannot overwrite the job.
     */
    @NotNull
    @Builder.Default
    @Column(name = "fencing_token", nullable = false)
    private Long fencingToken = 0L;

    /** Optional client-supplied key; unique per tenant to deduplicate submissions. */
    @Size(max = 255)
    @Column(name = "idempotency_key", updatable = false)
    private String idempotencyKey;

    /** Details of the most recent failure. */
    @Column(name = "error_message", columnDefinition = "text")
    private String errorMessage;

    /** When the current/last execution started. */
    @Column(name = "started_at")
    private Instant startedAt;

    /** When the job reached a terminal state. */
    @Column(name = "completed_at")
    private Instant completedAt;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    // Lifecycle callbacks only fire for JPA-managed writes. Native/bulk SQL updates
    // (e.g. future job claiming) must set updated_at themselves.
    @PrePersist
    void onCreate() {
        Instant now = now();
        createdAt = now;
        updatedAt = now;
        if (nextRunAt == null) {
            nextRunAt = now;
        }
    }

    @PreUpdate
    void onUpdate() {
        updatedAt = now();
    }

    /** Truncated to PostgreSQL's microsecond precision so in-memory and loaded values match. */
    private static Instant now() {
        return Instant.now().truncatedTo(ChronoUnit.MICROS);
    }
}
